'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const html=fs.readFileSync(path.join(root,'internal/web/ui/static/index.html'),'utf8');
const app=fs.readFileSync(path.join(root,'internal/web/ui/static/app.js'),'utf8');
const awg=fs.readFileSync(path.join(root,'internal/web/ui/static/awg.js'),'utf8');
assert.match(html,/data-tab="awg"/);
assert.match(html,/id="tab-awg"/);
assert.match(html,/id="awg-conf"/);
assert.match(html,/id="awg-upload"/);
assert.match(html,/src="\/assets\/awg.js"/);
assert.match(app,/awg: 'vpn'/);
assert.match(awg,/\/api\/v1\/awg\/profiles/);
assert.match(awg,/\/api\/v1\/awg\/import/);
assert.match(awg,/\/api\/v1\/awg\/delete/);
assert.match(awg,/new FormData/);
assert.match(awg,/\.append\('config'/);
console.log('AWG Web UI import and profile controls present');
